/** Every track in the catalog, for the credits surface. */
export const ALL_TRACKS: Track[] = Object.values(MOOD_TRACKS).flat();

/**
 * The queue for a scene. Built-in scenes draw from their mood bucket; a custom
 * scene is a single user-supplied URL, so it becomes a one-track queue.
 */
export function tracksForScene(scene: Scene): Track[] {
  if (scene.mood && MOOD_TRACKS[scene.mood]?.length) {
    return MOOD_TRACKS[scene.mood];
  }
  if (scene.musicUrl) {
    const [first] = scene.playlist;
    return [
      {
        id: `custom-${scene.id}`,
        title: first?.title ?? scene.name,
        artist: first?.artist ?? 'Custom source',
        duration: first?.duration ?? '--:--',
        src: scene.musicUrl,
      },
    ];
  }
  return [];
}
